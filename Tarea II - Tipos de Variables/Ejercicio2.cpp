#include <iostream>
using namespace std;

int main() {

	int valor1;
	int valor2;

	cout << "Ingrese el primer número entero: ";
	cin >> valor1;

	cout <<"Ingrese el segundo número entero: ";
	cin >> valor2;


	cout << "La suma es: " << valor1 + valor2 << endl;
	cout << "La resta es: " << valor1 - valor2 << endl;
	cout << "La multiplicación es: " << valor1 * valor2 << endl;

	return 0;
}
